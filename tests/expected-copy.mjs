/** Строка ТЗ без markdown-обрамления: "> ", "- ", "**", "N. " */
export const t = (n) =>
  TZ[n - 1]
    .replace(/^>\s?/, '')
    .replace(/^- /, '')
    .replace(/\*\*/g, '')
    .replace(/^\d+\.\s/, '')
    .trim();
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const nonEmpty = (ns) => ns.map(t).filter(Boolean);

/** FAQ: ТЗ:259–302 → [{ q, a: [абзацы] }] */
export const faq = (() => {
  const items = [];
  for (const n of range(259, 302)) {
    const raw = TZ[n - 1];
    const m = raw.match(/^\*\*\d+\.\s(.+)\*\*$/);
    if (m) items.push({ q: m[1], a: [] });
    else if (raw.trim()) items.at(-1).a.push(raw.trim());
  }
  return items;
})();

